QUESTION 16
Business Question:
Which sellers have the highest average order value?
======================================================

Expected Output:
- seller_id
- average_order_value
- total_orders

Business Insight:
Identify sellers that generate higher-value orders on average.
*/
SELECT
    seller_id,
    ROUND(
        AVG(order_value),
        2
    ) AS average_order_value,
    COUNT(*) AS total_orders
FROM (
    SELECT
        seller_id,
        order_id,
        SUM(price) AS order_value
    FROM order_items
    GROUP BY
        seller_id,
        order_id

) seller_orders
GROUP BY seller_id
ORDER BY average_order_value DESC
LIMIT 10;

