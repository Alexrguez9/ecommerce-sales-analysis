/*
======================================================
QUESTION 25
Business Question:
Which states have the highest percentage of delayed deliveries?
======================================================

Expected Output:
- customer_state
- delayed_orders
- total_orders
- delay_percentage

Business Insight:
Identify regions where logistics need improvement.
*/
SELECT
    c.customer_state,
    COUNT(*) FILTER (
        WHERE
            o.order_status='delivered'
            AND
            o.order_delivered_customer_date >
            o.order_estimated_delivery_date
    ) AS delayed_orders,
    COUNT(*) AS total_orders,
    ROUND(
        COUNT(*) FILTER (
            WHERE
                o.order_status='delivered'
                AND
                o.order_delivered_customer_date >
                o.order_estimated_delivery_date
        )::NUMERIC / COUNT(*) *100, 2
    ) AS delay_percentage
FROM customers c
INNER JOIN orders o
ON c.customer_id=o.customer_id
GROUP BY c.customer_state
ORDER BY delay_percentage DESC;


